test('짐작하면 안 되는 값: 날짜로 바뀐 학번, 범위 밖 숫자, 중복, 숫자만 있는 3자리', () => {
  const bad = (rows, re) => {
    const r = R.normalizeRoster(rows);
    assert.equal(r.students.length + r.errors.length >= 1, true);
    assert.match(r.errors.join('\n'), re);
    return r;
  };
  // 엑셀이 "1-1-5"를 날짜(2001-01-05 → 36896)로 바꿔 저장한 경우: 3학년 68반 96번으로 읽지 않는다
  assert.equal(bad([['학번', '이름'], [36896, '김하늘']], /읽지 못했습니다/).students.length, 0);
  assert.equal(R.parseStudentId('19905'), null);
  bad([['학년', '반', '번호', '이름'], [1, 1, 150, '김하늘']], /읽지 못했습니다|범위/);
  const dup = bad([['학번', '이름'], [10105, '김하늘'], [10105, '이지호']], /겹칩니다/);
  assert.equal(dup.errors.length, 1);
  bad([['학번', '이름'], ['115', '김하늘']], /읽지 못했습니다/);
});

test('가나다반·A반처럼 숫자가 아닌 반은 읽지 못한다고 알려 준다(임의로 번호를 붙이지 않는다)', () => {
  const r = R.normalizeRoster([['학년', '반', '번호', '이름'], [1, '가', 1, '김하늘'], [1, 'A', 2, '이지호']]);
  assert.equal(r.students.length, 0);
  assert.equal(r.errors.length, 2);
  assert.match(r.errors[0], /반을\(를\) 읽지 못했습니다/);
});

test('엑셀 "유니코드 텍스트"(UTF-16) 저장 파일', async () => {
  const text = '﻿학번\t이름\r\n10105\t김하늘\r\n';
  const buf = Buffer.from(text, 'utf16le');
  const r = R.normalizeRoster(await R.bufferToRows(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length)));
  assert.deepEqual(flat(r), ['1-1-5 김하늘']);
});
