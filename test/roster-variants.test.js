test('E. 한 칸에 전부: 붙여 쓴 글, 반별 표의 "5. 김하늘"', () => {
  ok([['1학년1반5번 김하늘'], ['1학년 1반 6번 이지호']], ['1-1-5 김하늘', '1-1-6 이지호']);
  ok([['1학년 2반'], ['1. 김하늘'], ['2. 이지호'], ['3번 박보람']], ['1-2-1 김하늘', '1-2-2 이지호', '1-2-3 박보람']);
  ok([['1-1-5 응우옌 티 란'], ['1-1-6 김하늘']], ['1-1-5 응우옌 티 란', '1-1-6 김하늘']);
});

test('F. 병합된 학급 칸(첫 줄에만 값)과 제목 줄의 "2026학년도 1학년 3반"', () => {
  ok([['1학년 1반', 1, '김하나'], ['', 2, '이두리'], ['1학년 2반', 1, '박세찬'], ['', 2, '최도윤']], ['1-1-1 김하나', '1-1-2 이두리', '1-2-1 박세찬', '1-2-2 최도윤']);
  // "2026학년도"의 26을 학년으로 읽으면 안 된다
  ok([['2026학년도 1학년 3반 학생 명부'], ['번호', '성명', '비고'], [1, '김하늘', ''], [2, '이지호', '']], ['1-3-1 김하늘', '1-3-2 이지호']);
  const r = R.normalizeRoster([['2026학년도 학생 명부'], ['번호', '성명'], [1, '김하늘']]);
  assert.equal(r.students.length, 0);
  assert.equal(r.need.grade, 1);
});

