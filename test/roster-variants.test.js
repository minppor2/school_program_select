test('I. 학년(반)이 아예 없는 파일은 한 번 물어 채운다', () => {
  const rows = [['반', '번호', '이름'], [1, 1, '김하나'], [2, 1, '이두리']];
  const r = R.normalizeRoster(rows);
  assert.equal(r.students.length, 0);
  assert.deepEqual(r.need, { grade: 2, class: 0 });
  ok(rows, ['3-1-1 김하나', '3-2-1 이두리'], { defaultGrade: 3 });
  ok([['번호', '이름'], [1, '김하나'], [2, '이두리']], ['3-2-1 김하나', '3-2-2 이두리'], { defaultGrade: 3, defaultClass: 2 });
  // 파일에 적힌 값이 있으면 물어 채운 값보다 우선한다
  ok([['학번', '이름'], [10105, '김하늘']], ['1-1-5 김하늘'], { defaultGrade: 3, defaultClass: 2 });
});

